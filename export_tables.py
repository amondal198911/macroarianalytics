#!/usr/bin/env python3
"""Write src/js/stat-tables.js: published critical-value tables used by the in-browser statistics engine.

  * MacKinnon (1994) response surfaces for unit-root / cointegration p-values and MacKinnon (2010) critical values
    (as implemented in statsmodels.tsa.adfvalues).
  * KPSS (1992) critical values.
  * Zivot and Andrews (1992) simulated quantiles (statsmodels ZivotAndrewsUnitRoot).
  * Johansen trace and maximum-eigenvalue critical values, MacKinnon, Haug and Michelis (1999) (statsmodels coint_tables).
  * Edgerton and Wells (1994) CUSUM-of-squares approximation constants (statsmodels RecursiveLS).
  * Andrews (1993) sup-F (sup-Wald) asymptotic quantiles with 15% trimming, simulated here (seeded, reproducible).
Run once after upgrading statsmodels:  python scripts/export_tables.py
"""
import json
from pathlib import Path
import numpy as np
from statsmodels.tsa import adfvalues as av
from statsmodels.tsa import coint_tables as ct
from statsmodels.tsa.stattools._stattools import ZivotAndrewsUnitRoot
from statsmodels.regression import recursive_ls as rls

ROOT = Path(__file__).resolve().parent.parent


def L(a):
    return np.where(np.isfinite(np.asarray(a, float)), np.asarray(a, float), 1e9).tolist()


mack = {}
for reg in ['n', 'c', 'ct']:
    mack[reg] = dict(max=L(av._tau_maxs[reg]), min=L(av._tau_mins[reg]), star=L(av._tau_stars[reg]),
                     small=np.asarray(av._tau_smallps[reg]).tolist(), large=np.asarray(av._tau_largeps[reg]).tolist(),
                     crit2010=np.asarray(av.tau_2010s[reg]).tolist())
za = ZivotAndrewsUnitRoot()
za_tab = {m: np.asarray(za._za_critical_values[m]).tolist() for m in ['c', 't', 'ct']}
joh = dict(maxeig={str(p): [ct.c_sja(n, p).tolist() for n in range(1, 13)] for p in (-1, 0, 1)},
           trace={str(p): [ct.c_sjt(n, p).tolist() for n in range(1, 13)] for p in (-1, 0, 1)})
cusumsq = rls._cusum_squares_scalars.tolist()

# Andrews (1993) sup-Wald with trimming 0.15: sup over lambda of |B_k(lambda)|^2 / (lambda (1 - lambda)),
# B_k = k independent Brownian bridges. Simulated on a grid of 2,000 steps, 40,000 draws (seed fixed).
rng = np.random.default_rng(19931993)
N, R = 2000, 40000
lam = np.arange(1, N + 1) / N
keep = (lam >= 0.15) & (lam <= 0.85)
w = (lam * (1 - lam))[keep]
qs = [0.50, 0.75, 0.80, 0.85, 0.90, 0.925, 0.95, 0.975, 0.99, 0.995]
supw = {}
for k in range(1, 9):
    out = np.empty(R)
    for b in range(0, R, 2000):
        z = rng.standard_normal((2000, k, N)) / np.sqrt(N)
        W = np.cumsum(z, axis=2)
        Bb = W - lam[None, None, :] * W[:, :, -1:]
        stat = (Bb[:, :, keep] ** 2).sum(axis=1) / w[None, :]
        out[b:b + 2000] = stat.max(axis=1)
    supw[str(k)] = [round(float(np.quantile(out, q)), 3) for q in qs]
    print('k', k, 'sup-Wald 90/95/99%:', supw[str(k)][4], supw[str(k)][6], supw[str(k)][8])

tables = dict(mackinnon=mack, kpss={'c': [0.347, 0.463, 0.574, 0.739], 'ct': [0.119, 0.146, 0.176, 0.216], 'p': [0.10, 0.05, 0.025, 0.01]},
              za=za_tab, johansen=joh, cusumsq=cusumsq, supwald=dict(q=qs, k=supw, trim=0.15,
              note='Simulated asymptotic quantiles of the Andrews (1993) sup-Wald statistic; divide by k for sup-F.'))
js = ('/* Critical-value tables for the statistics engine. Generated by scripts/export_tables.py from statsmodels '
      '(MacKinnon 1994/2010; KPSS 1992; Zivot-Andrews 1992; MacKinnon-Haug-Michelis 1999; Edgerton-Wells 1994) '
      'and a seeded simulation of Andrews (1993). Do not edit by hand. */\n'
      'window.MA_TABLES=' + json.dumps(tables, separators=(',', ':')) + ';\n')
(ROOT / 'src' / 'js').mkdir(parents=True, exist_ok=True)
(ROOT / 'src' / 'js' / 'stat-tables.js').write_text(js, encoding='utf-8')
print('wrote', len(js), 'bytes')
